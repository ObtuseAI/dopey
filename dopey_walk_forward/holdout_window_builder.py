def _template_to_window(template: dict, sequence_id: int) -> RegimeHoldoutWindow:
    """Materialize a compact template into a RegimeHoldoutWindow."""
    challenge_template = template.get("challenge")
    challenge_context = None
    if challenge_template is not None:
        # challenge_template is already a CrossFamilyChallengeWindow from make_challenge.
        challenge_context = CrossFamilyChallengeContext.from_challenge(challenge_template)
    return RegimeHoldoutWindow(
        window_id=template["window_id"],
        regime_tag=template["regime_tag"],
        category=template["category"],
        sector_context=template["sector"],
        macro_context=template["macro"],
        iv_surface_context=template["iv_surface"],
        skew_term_context=template["skew_term"],
        liquidity_context=template["liquidity"],
        pattern_context=template["pattern"],
        challenge_context=challenge_context,
        expected_family_pressure=template["expected_family_pressure"],
        preferred_families=tuple(template.get("preferred_families", ())),
        penalized_families=tuple(template.get("penalized_families", ())),
        holdout_purpose=template["holdout_purpose"],
        sequence_id=sequence_id,
        notes=template.get("notes", ""),
    )


def build_regime_holdout_corpus_v2(
    seed: str = "dopey-regime-holdout-corpus-v2-v1",
    corpus_id: str | None = None,
) -> RegimeHoldoutCorpus:
    """Build the canonical v2 corpus (32 windows)."""
    if corpus_id is None:
        corpus_id = f"dopey-regime-holdout-corpus-v2-{seed}"
    windows = tuple(
        _template_to_window(template, sequence_id=1000 + i)
        for i, template in enumerate(V2_WINDOW_TEMPLATES)
    )
    regime_set: set[str] = set()
    sector_set: set[str] = set()
    macro_set: set[str] = set()
    liquidity_set: set[str] = set()
    iv_set: set[str] = set()
    for w in windows:
        regime_set.add(w.regime_tag)
        sector_set.add(w.sector_context.sector)
        macro_set.add(w.macro_context.event_label)
        liquidity_set.add(w.liquidity_context.stress_label)
        iv_set.add(w.iv_surface_context.transition_label)
    return RegimeHoldoutCorpus(
        corpus_id=corpus_id,
        version=CORPUS_V2_VERSION,
        windows=windows,
        regime_coverage=tuple(sorted(regime_set)),
        sector_coverage=tuple(sorted(sector_set)),
        macro_coverage=tuple(sorted(macro_set)),
        liquidity_stress_coverage=tuple(sorted(liquidity_set)),
        volatility_transition_coverage=tuple(sorted(iv_set)),
    )


def category_window_count(corpus: RegimeHoldoutCorpus) -> dict[str, int]:
    """Count windows per category in the corpus."""
    counts: dict[str, int] = {c: 0 for c in V2_CATEGORIES}
    for w in corpus.windows:
        counts[w.category] = counts.get(w.category, 0) + 1
    return counts


def additional_v2_window_count() -> int:
    return len(V2_WINDOW_TEMPLATES)
